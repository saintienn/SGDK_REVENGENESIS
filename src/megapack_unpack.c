u32 mp_call_megaunp(const u8 *src, u8 *dst) {
    static mp_bs_t state;
    state.cmp  = 0;
    state.src  = src;
    state.used = 0;
    u32 tiles_num = mp_parse_header(&state);
    mp_process_tiles(&state, dst, tiles_num);
    return tiles_num * MP_TILE_SIZE;
}
