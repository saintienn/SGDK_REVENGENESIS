/* ── Funções de bitstream RESTAURADAS (apenas para uso do linerep em C) ── */

static __attribute__((always_inline)) u16 mp_read_bits(mp_bs_t *s, u8 num_bits) {
    u32 cmp  = s->cmp;
    u8  used = s->used;
    const u8 *src = s->src;

    if (used == 0) {
        cmp = ((u32)src[0] << 24) | ((u32)src[1] << 16);
        src += 2;
        used = 16;
    }

    if (num_bits <= used) {
        u16 result = (u16)(cmp >> (32 - num_bits));
        cmp <<= num_bits;
        used -= num_bits;
        s->cmp = cmp;
        s->used = used;
        s->src = src;
        return result;
    }

    u8 first = used;
    u16 hi = (u16)(cmp >> (32 - first));
    num_bits -= first;

    cmp = ((u32)src[0] << 24) | ((u32)src[1] << 16);
    src += 2;
    used = 16;

    u16 result = (hi << num_bits) | (u16)(cmp >> (32 - num_bits));
    cmp <<= num_bits;
    used -= num_bits;

    s->cmp = cmp;
    s->used = used;
    s->src = src;
    return result;
}

static u32 mp_get_stream(mp_bs_t *s, u32 range) {
top:
    if (range > 0x100) {
        range--;
        u32 low = (range & 0xFF) + 1;
        u32 hi  = (range >> 8) + 1;
        u32 xhi = mp_get_stream(s, hi);
        if (xhi > 0)
            return mp_read_bits(s, 8) + (xhi - 1) * 256 + low;
        range = low;
        goto top;
    }

    u32 bc = mp_log2_lut[range];
    u32 unused = (1u << (bc + 1)) - range;
    u32 x = mp_read_bits(s, (u8)bc);
    if (x < unused) return x;
    return ((x << 1) | mp_read_bits(s, 1)) - unused;
}

static __attribute__((always_inline)) u8 mp_pixstream(mp_bs_t *s, u16 col_set) {
    u8 lo = (u8)col_set;
    u8 hi = (u8)(col_set >> 8);
    register u8 loc = mp_bitcount[lo];
    register u8 n   = loc + mp_bitcount[hi];
    u16 idx = (u16)mp_get_stream(s, n);
    if (idx < loc)
        return mp_nth_set_bit[(u16)lo * 8 + idx];
    return mp_nth_set_bit[(u16)hi * 8 + (idx - loc)] + 8;
}

static __attribute__((always_inline)) u8 mp_mpixstream(mp_bs_t *s, u8 pixel, u16 pixels) {
    pixels &= ~(1u << pixel);
    return mp_pixstream(s, pixels);
}

/* ── Helpers 4bpp ── */
static inline void mp_set_pixel_4bpp(u8 *tile, u8 x, u8 y, u8 pix) {
    u16 offs = (y << 2) + (x >> 1);
    if (x & 1)
        tile[offs] = (tile[offs] & 0xF0) | (pix & 0x0F);
    else
        tile[offs] = (tile[offs] & 0x0F) | (pix << 4);
}

static inline u8 mp_get_pixel_4bpp(const u8 *tile, u8 x, u8 y) {
    u8 v = tile[(y << 2) + (x >> 1)];
    if (x & 1)
        return v & 0x0F;
    return v >> 4;
}

